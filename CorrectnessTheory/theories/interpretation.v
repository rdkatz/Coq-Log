Proof.
intros Hcrt t.
case (dec_setTerm t1) as [HsetTerm1 | ?].
- assert (HsetTerm2 : setTerm t2).
    now apply (clos_rel_term_setTerm Hcrt).
  destruct (setTerm_exists_listSetC _ HsetTerm1) as [lt1 ->].
  destruct (setTerm_exists_listSetC _ HsetTerm2) as [lt2 ->].
  split; try now apply axiomE_aux.
  apply axiomE_aux.
  now apply clos_rel_term_sym.
- assert (Hneg_setTerm2 : ~ setTerm t2).
    intro Habs.
    absurd (setTerm t1); try assumption.
    apply clos_rel_term_setTerm with (t1 := t2); try assumption.
    now apply clos_rel_term_sym.
  now simpl; split; intros [Habs _]; contradiction.
Qed.

