(* interpretation  *)
(*******************)

Notation " x === y " := (clos_rel_term x y) (at level 70, no associativity).

Notation " x =/= y " := (complement clos_rel_term x y) (at level 70, no associativity).

(* interpretation of primitive constraints *)
Definition interpretPC (pc : primitiveConstraint) :=
  match pc with
  | Eq t1 t2 => t1 === t2
  | Neq t1 t2 => t1 =/= t2
  | Mem t1 t2 => ((setTerm t2) /\ (exists t, (t === t1) /\ (In t (listElements t2))))
  | Nmem t1 t2 => ~((setTerm t2) /\ (exists t, (t === t1) /\ (In t (listElements t2))))
  | FalseC => False
  | IsSet t => setTerm t
  end.

(* interpretation of constraints *)
Fixpoint interpretC (c : constraint) :=
  match c with
  | nil => True
  | pc :: lpc => ((interpretPC pc) /\ (interpretC lpc))
  end.

