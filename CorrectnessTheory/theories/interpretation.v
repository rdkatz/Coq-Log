(* a generalization of remove to lists of terms *)
Fixpoint remove_interpret (t : term) (lt : list term) : list term :=
  match lt with
  | nil => nil
  | t' :: lt' => if (clos_rel_term_dec t t') then (remove_interpret t lt') else t' :: (remove_interpret t lt')
  end.

Lemma remove_interpret_cons t t' lt :
  t === t' -> remove_interpret t' (t :: lt) = remove_interpret t' lt.
Proof.
intros Hinter.
simpl; case (clos_rel_term_dec t' t) as [_ | Habs]; try reflexivity.
absurd (t' === t); try assumption.
now apply clos_rel_term_sym.
Qed.

Lemma remove_interpret_eq_nil t lt :
  remove_interpret t lt = nil <-> (forall t', In t' lt -> t' === t).
Proof.
split.
- elim lt.
  + intros _ ? ?; try contradiction.
  + intros t' lt' Hind.
    simpl; case (clos_rel_term_dec t t') as [Hinter | _].
    * intros Hnil t'' HIn.
      case HIn as [-> | HIn]; try now apply clos_rel_term_sym.
      now apply Hind.
    * intros Habs.
      absurd (In t' nil); try now apply in_nil.
      rewrite <- Habs.
      now apply in_eq.
- elim lt; try reflexivity.
  intros t' lt' Hind Hforall.
  assert (Hinter : t' === t).
    apply Hforall.
    now apply in_eq.
  rewrite (remove_interpret_cons _ Hinter).
  apply Hind.
  intros t'' HIn.
  apply Hforall.
  now apply in_cons.
Qed.

Lemma interpret_remove_interpret t t' lt :
  t === t' -> remove_interpret t lt = remove_interpret t' lt.
Proof.
intro Hinter.
elim lt; try reflexivity.
intros t'' lt'' Hind.
simpl; case (clos_rel_term_dec t t'') as [Hinter' | Hneq_inter].
- case (clos_rel_term_dec t' t'') as [? | ?]; try assumption.
  absurd (t' === t''); try assumption.
  apply t_trans with (y := t); try assumption.
  now apply clos_rel_term_sym.
- case (clos_rel_term_dec t' t'') as [? | ?]; try now rewrite Hind.
  absurd (t === t''); try assumption.
  now apply t_trans with (y := t').
Qed.

Lemma incl_remove_interpret t lt :
  incl (remove_interpret t lt) lt.
Proof.
elim lt; try now apply incl_nil_l.
intros t' lt' Hind.
simpl; case (clos_rel_term_dec t t') as [_ | _]; try now apply incl_tl.
intros t'' HIn.
case HIn as [-> | HIn]; try now apply in_eq.
apply in_cons.
now apply Hind.
Qed.

Lemma length_remove_interpret t lt :
  length (remove_interpret t lt) <= length lt.
Proof.
elim lt; try now apply le_n.
intros t' lt' Hind.
now simpl; case (clos_rel_term_dec t t') as [_ | ?]; [apply le_S | apply le_n_S].
Qed.

Lemma in_remove_interpret t t' lt :
  In t' lt ->
    ~ (t === t') <-> In t' (remove_interpret t lt).
Proof.
elim lt; try contradiction.
intros t'' lt'' Hind HIn.
case HIn as [-> | HIn'].
- split.
  + intro Hneg_inter.
    simpl; case (clos_rel_term_dec t t') as [? | ?]; try now absurd (t === t').
    now apply in_eq.
  + simpl; case (clos_rel_term_dec t t') as [? | ?]; try now intro; assumption.
    intro HIn.
    apply Hind; try assumption.
    now apply incl_remove_interpret with (t := t).
- split.
  + intro Hneg_inter.
    simpl; case (clos_rel_term_dec t t'') as [_ | _]; try now apply Hind.
    apply in_cons.
    now apply Hind.
  + simpl; case (clos_rel_term_dec t t'') as [_ | ?]; try now apply Hind.
    intro HIn.
    case HIn as [-> | ?]; try assumption.
    now apply Hind.
Qed.

Lemma incl_interpret_remove_interpret t lt1 lt2 :
  incl_interpret lt1 lt2 ->
    incl_interpret (remove_interpret t lt1) (remove_interpret t lt2).
Proof.
intros Hincl_inter t1 HIn.
assert (HIn1 : In t1 lt1).
  now apply incl_remove_interpret with (t := t).
