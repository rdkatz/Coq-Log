Lemma interpret_dec_aux t lt :
  (forall t', In t' lt -> {t === t'} + {~ (t === t')}) ->
    {incl_interpret (t :: nil) lt} + {~ (incl_interpret (t :: nil) lt)}.
Proof.
elim lt.
- intros _.
  right; intro Habs.
  assert (HIn : In t (t :: nil)).
    now apply in_eq.
  now destruct (Habs _ HIn) as [? [_ ?]].
- intros t' lt' Hind H.
  assert (Hdec1 : {t === t'} + {~ t === t'}).
    apply H.
    now apply in_eq.
  assert (Hdec2 : {incl_interpret (t :: nil) lt'} + {~ incl_interpret (t :: nil) lt'}).
    apply Hind.
    intros t'' HIn.
    apply H.
    now apply in_cons.
  case Hdec1 as [Hd1 | Hnd1].
  + left.
    intros t'' HIn.
    case HIn as [-> | ]; try contradiction.
    exists t'; split; try now apply in_eq.
    now apply clos_rel_term_sym.
  + case Hdec2 as [Hd2 | Hnd2].
    * now left; apply incl_interpret_tl.
    * right; intro Habs.
      assert (HIn : In t (t :: nil)).
        now apply in_eq.
      destruct (Habs _ HIn) as [t'' [Habs' HIn']].
      case HIn' as [Heq | HIn''].
      -- absurd (t === t'); try assumption.
         apply clos_rel_term_sym.
         now rewrite Heq.
      -- absurd (incl_interpret (t :: nil) lt'); try assumption.
         intros t''' HIn'.
         case HIn' as [-> | ]; try contradiction.
         now exists t''.
Qed.

