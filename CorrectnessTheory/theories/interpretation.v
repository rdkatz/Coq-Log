(* relation associated with an elementary application of the absorption axiom *)
Definition relAb_term (t1 t2 : term) : Prop :=
  match t1 with
  | Var _ => t2 = t1
  | SetC t1' (SetC t2' t3') => match t2 with
                               | Var v => False
                               | SetC t4' t5' => ((t1' = t2') /\ (t1' = t4') /\ (t3' = t5'))
                               | OTerm _ _ => False
                               | EmptySet => False
                               end
  | SetC _ _ => t2 = t1
  | OTerm _ _ => t2 = t1
  | EmptySet => t2 = t1
  end.

(* relation associated with an elementary application of the left-commutativity axiom *)
Definition relCl_term (t1 t2 : term) : Prop :=
  match t1 with
  | Var _ => t2 = t1
  | SetC t1' (SetC t2' t3') => match t2 with
                               | Var v => False
                               | SetC t4' (SetC t5' t6') => ((t1' = t5') /\ (t2' = t4') /\ (t3' = t6'))
                               | SetC t4' _ => t2 = t1
                               | OTerm s l => False
                               | EmptySet => False
                               end
  | SetC _ _ => t2 = t1
  | OTerm _ _ => t2 = t1
  | EmptySet => t2 = t1
  end.

(* relation associated with an elementary application of the absorption or left-commutativity axioms *)
Definition relAbCl_term (t1 t2 : term) : Prop :=
  (t1 = t2) \/ (relAb_term t1 t2) \/ (relAb_term t2 t1) \/ (relCl_term t1 t2).

(* relation associated with a structural application of the absorption or left-commutativity axioms *)
Fixpoint rel_term (t1 t2 : term) : Prop :=
  match t1 with
  | Var _ => t2 = t1
  | SetC t1' t2' => match t2 with
                    | Var _ => False
                    | SetC t3' t4' => ((relAbCl_term t1 t2) \/
                                      ((t2' = t4') /\ (rel_term t1' t3')) \/
                                      ((t1' = t3') /\ (rel_term t2' t4')))
                    | OTerm s l => False
                    | EmptySet => False
                    end
  | OTerm s1 l1 => match t2 with
                   | Var _ => False
                   | SetC t3' t4' => False
                   | OTerm s2 l2 => let rel_list :=
                                        (fix rel_list (l1 l2 : list term) {struct l1} : Prop :=
                                         match l1 with
                                         | nil => match l2 with
                                                  | nil => True
                                                  | t :: lt => False
                                                  end
                                         | t :: lt => match l2 with
                                                      | nil => False
                                                      | t' :: lt' => rel_term t t' /\ rel_list lt lt'
                                                      end
                                         end) in
                                 ((s1 = s2) /\ (length l1 = length l2) /\ (rel_list l1 l2))
                   | EmptySet => False
                   end
  | EmptySet => t2 = t1
  end.

(* smallest equivalence relation generated by rel_term *)
Definition clos_rel_term :=  clos_trans term rel_term.

