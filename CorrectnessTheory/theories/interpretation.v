Lemma rel_term_refl :
  Reflexive rel_term.
Proof.
intro t.
set (P := fun (n : nat) => (forall t', ((sizet t') <= n) -> rel_term t' t')).
enough (H : (forall n, (P n))).
  apply (H (sizet t)).
  now apply le_n.
intro n.
induction n as [ | n Hind].
- intros t' Hsizet.
  now absurd (sizet t' <= 0); [apply sizet_gte_1 | assumption].
- intro t'.
  case t'; try now intros.
  + intros; left.
    now apply relAbCl_term_refl.
  + intros ? lt Hsizet; split; try reflexivity.
    split; try reflexivity.
    revert Hsizet.
    elim lt; try trivial.
    intros t'' lt' Hind' Hsizet.
    split.
    * apply Hind.
      apply le_S_n.
      apply Nat.le_trans with (m := sizet (OTerm l (t'' :: lt'))); try assumption.
