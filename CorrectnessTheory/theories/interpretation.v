Lemma mem_neg_rel_term (t t1 t2 : term) :
  interpretPC (t \:s t1) -> interpretPC (t :s t2) -> t1 =/= t2.
Proof.
intros Hinter [HsetTerm2 [t' [Hclos_rel_term' HIn]]] Hclos_rel_term.
