Lemma clos_rel_term_elem_Mem t t1 t2 :
  t1 === t2 -> interpretPC (t1 :s t) <-> interpretPC (t2 :s t).
Proof.
intro Hequiv.
split; intros [? [t' [? ?]]]; split; try assumption.
- exists t'; split; try assumption.
  now apply t_trans with (y := t1).
- exists t'; split; try assumption.
  apply t_trans with (y := t2); try assumption.
  now apply clos_rel_term_sym.
Qed.

Lemma interpretC_app c1 c2 :
  interpretC (c1 ++ c2) <-> (interpretC c1) /\ (interpretC c2).
Proof.
induction c1 as [| pc c Hind]; try now split.
split.
- intros [? ?].
  assert (Hand : interpretC c /\ interpretC c2).
    now apply Hind.
  destruct Hand.
  split; try assumption.
  now split.
- intros [[? ?] ?].
  split; try assumption.
  now apply Hind; split.
Qed.

Lemma interpretC_iff (c : constraint) :
  (interpretC c) <-> (forall pc, In pc c -> (interpretPC pc)).
Proof.
split.
- elim c; try contradiction.
  intros pc' c' Hind [? ?] pc'' HIn.
  now case HIn as [<- | HIn]; [assumption | apply Hind].
- elim c; try now simpl.
  intros pc' c' Hind H.
  split.
  + apply H.
    now apply in_eq.
  + apply Hind.
    intros pc'' HIn.
    apply H.
    now apply in_cons.
Qed.

