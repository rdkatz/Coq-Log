(* returns a list of primitive constraints of the form IsSet t'
   if the subterm t' of the term t is required to represent a set *)
Fixpoint find_set (t : term) : constraint :=
  match t with
  | Var _ => nil
  | SetC t1 t2 =>
     match t2 with
     | SetC _ _ => (find_set t1) ++ (find_set t2)
     | EmptySet => (find_set t1)
     | _ => (find_set t1) ++ (find_set t2) ++ (IsSet t2) :: nil
     end
  | OTerm _ l =>
     let find_setList :=
     (fix find_setList (l: list term) {struct l} : constraint :=
       match l with
       | nil => nil
       | t :: lt => (find_set t) ++ (find_setList lt)
     end) in
     find_setList l
  | EmptySet => nil
  end.

(* returns a list of primitive constraints of the form IsSet t if the subterm t
   of the primitive constraint pc is required to represent a set *)
Definition set_inferPC (pc : primitiveConstraint) : constraint :=
  match pc with
  | t1 == t2 => (find_set t1) ++ (find_set t2)
  | t1 \== t2 => (find_set t1) ++ (find_set t2)
  | t1 :s t2 => match t2 with
                | EmptySet => find_set t1 
                | SetC t3 t4 => (find_set t1) ++ (find_set t2)
                | _ => (find_set t1) ++ (find_set t2) ++ ((IsSet t2) :: nil)
                end
  | t1 \:s t2 => match t2 with
                 | EmptySet => find_set t1
                 | SetC t3 t4 => (find_set t1) ++ (find_set t2)
                 | _ => (find_set t1) ++ (find_set t2) ++ ((IsSet t2) :: nil)
                 end
  | FalseC => nil
  | IsSet t => (find_set t)
  end.

(* returns a list of primitive constraints of the form IsSet t if the subterm t
   of the constraint c is required to represent a set *)
Fixpoint set_infer (c : constraint) : constraint :=
  match c with
  | nil => nil
  | pc :: ct => (set_inferPC pc) ++ (set_infer ct)
  end.

(* requires all primitive constraints generated by set_infer c to be in c *)
Definition sort_complete (c : constraint) :=
  incl (set_infer c) c.

(* requires all set constraints induced by the structure of t 
   to be satisfied after applying sigma *)
Fixpoint respectsSorts (sigma : substitution) (t : term) : Prop :=
  match t with
  | Var _ => True
  | EmptySet => True
  | OTerm _ l =>
 let respectsSortsList :=
     (fix respectsSortsList sigma l {struct l} : Prop :=
  match l with
  | nil => True
  | t :: lt =>
      respectsSorts sigma t /\
      respectsSortsList sigma lt
   end) in
     respectsSortsList sigma l
  | SetC t1 t2 =>
      respectsSorts sigma t1 /\
      respectsSorts sigma t2 /\
      setTerm (applySubstitution sigma t2)
  end.

(* requires all set constraints induced by the structure of 
   the primitive constraint pc to be satisfied after applying sigma *)
Definition respectsSortsPC (sigma : substitution) (pc : primitiveConstraint) : Prop :=
  match pc with
  | t1 == t2 => respectsSorts sigma t1 /\ respectsSorts sigma t2
  | t1 \== t2 => respectsSorts sigma t1 /\ respectsSorts sigma t2
  | t1 :s t2 => respectsSorts sigma t1 /\ respectsSorts sigma t2 /\
                setTerm (applySubstitution sigma t2)
  | t1 \:s t2 => respectsSorts sigma t1 /\ respectsSorts sigma t2 /\
                 setTerm (applySubstitution sigma t2)
  | FalseC => True
  | IsSet t => respectsSorts sigma t /\ setTerm (applySubstitution sigma t)
  end.

(* requires all set constraints induced by the structure of 
   the constraint c to be satisfied after applying sigma *)
Fixpoint respectsSortsC (sigma : substitution) (c : constraint) : Prop :=
  match c with
  | nil => True
  | pc :: ct => (respectsSortsPC sigma pc) /\ (respectsSortsC sigma ct)
  end.

