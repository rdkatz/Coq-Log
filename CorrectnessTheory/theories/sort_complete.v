Lemma sort_complete_set_infer c :
  sort_complete c -> forall pc, In pc c -> incl (set_inferPC pc) c.
Proof.
intros Hsort_c pc HIn.
enough (He : incl (set_inferPC pc) (set_infer c)).
  now apply incl_tran with (m := (set_infer c)).
revert HIn.
elim c; try contradiction.
intros pc' c' Hind HIn.
case HIn as [-> | HIn']; try now apply incl_appl.
apply incl_appr.
now apply Hind.
Qed.

